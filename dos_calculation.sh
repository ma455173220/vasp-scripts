#!/bin/bash

# Display help information
display_help() {
    echo "---------------------------------------------------------"
    cat <<EOL
Usage: $0 [options]
Options:
  -h            Display this help message
  -e E1 E2      Set EMIN and EMAX values in INCAR (requires two additional arguments)
Example: $0 -e -1.0 1.0
EOL
    exit 1
}

# Shared helpers (vasp_common.sh): next to this script, else on PATH
_lib="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/vasp_common.sh"; [ -f "$_lib" ] || _lib=$(command -v vasp_common.sh || true)
[ -n "$_lib" ] || { echo "ERROR: vasp_common.sh not found (next to this script or on PATH)" >&2; exit 1; }
source "$_lib"

# Submission script: header-limited scan (first 4 KB), asks if there are several ($RUNSCRIPT overrides)
SUBMISSION_SCRIPT=$(find_runscript)
[ -z "$SUBMISSION_SCRIPT" ] && echo -e "\033[33mWARNING:\033[0m no #PBS/#SBATCH submission script found (or none selected) in $PWD"
COPY_FILES_NEEDED="INCAR POSCAR POTCAR $SUBMISSION_SCRIPT"
LN_FILES_NEEDED="CHGCAR"
NEW_DIRECTORY="DOS"

echo "---------------------------------------------------------"

# Create directory if it doesn't exist
if [ ! -d "$NEW_DIRECTORY" ]; then
    mkdir "$NEW_DIRECTORY" && echo -e "$NEW_DIRECTORY directory created!"
    echo "---------------------------------------------------------"
fi

# Function to check if a file exists and is non-empty
check_file() {
    if [ ! -s "$1" ]; then
        echo -e "\033[31mERROR:\033[0m $1 does not exist or is an empty file!"
        echo "---------------------------------------------------------"
        exit 1
    fi
}

# Copy necessary files to the new directory
for file in $COPY_FILES_NEEDED; do
    check_file "$file"
    cp "$file" "$NEW_DIRECTORY" && echo "'$file' -> '$NEW_DIRECTORY/$file'"
done

# Define the ln_file function
ln_file() {
    local file="CHGCAR"
    check_file "$file"
    cd "$NEW_DIRECTORY" && ln -s "../$file" . && echo "'$file' -> '$NEW_DIRECTORY/$file'"
    cd ..
}

# Define the file_editor function
file_editor() {
    cd "$NEW_DIRECTORY"
    incar_set ICHARG 11
    incar_comment LAECHG
    incar_set NSW 0
    incar_set IBRION -1
    incar_set LWAVE .FALSE.
    incar_set LCHARG .FALSE.
    incar_set LORBIT 11
    incar_set NEDOS 3000
    grep -iE "^[[:space:]]*(NSW|LORBIT|IBRION|LCHARG|LWAVE|ICHARG)[[:space:]]*=" INCAR | awk -F "#" '{print $1}'
    if [[ "$(incar_get ICHARG)" != "11" || "$(incar_get NSW)" != "0" ]]; then
        echo -e "\033[31mERROR:\033[0m INCAR in $NEW_DIRECTORY does not have ICHARG = 11 / NSW = 0 after editing. Aborting."
        exit 1
    fi
    cd ..
}

# Define the file_editor_energy_range function
file_editor_energy_range() {
    echo "---------------------------------------------------------"
    cd "$NEW_DIRECTORY"
    # Check if both E1 and E2 arguments are provided
    if [[ -n "$2" && -n "$3" ]]; then
        incar_set EMIN "$2"
        incar_set EMAX "$3"
        echo "EMIN set to $2, EMAX set to $3 in INCAR"
    else
        echo -e "\033[31mERROR:\033[0m Missing arguments for -e flag. Usage: sh script.sh -e E1 E2"
        echo "---------------------------------------------------------"
        exit 1
    fi
    cd ..
}

# Define the kpoints_vaspkit_generation function
kpoints_vaspkit_generation() {
    cd "$NEW_DIRECTORY"
    echo -e "102\n2\n0.02\n" | vaspkit 1>/dev/null
    echo -e "'Kmesh_0.02' generated by vaspkit!"
    cd ..
}

# Process command line options
while getopts ":he:" opt; do
    case $opt in
        h) display_help ;;
        e) file_editor_energy_range -e "$2" "$3" ;;
        \?) echo "Invalid option: -$OPTARG. Use -h for help." >&2; exit 1 ;;
    esac
done

echo "---------------------------------------------------------"
file_editor
echo "---------------------------------------------------------"
kpoints_vaspkit_generation
ln_file
echo "---------------------------------------------------------"

