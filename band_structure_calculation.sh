#!/bin/bash
# Usage: band_structure_calculation.sh [--2d | --3d]
#   k-path: vaspkit 302 (2D) if the largest vacuum gap along c is > 8 Å, else 303 (bulk);
#   --2d / --3d (or KPATH_TASK=302/303) override the detection
case "$1" in
    --2d) KPATH_TASK=302 ;;
    --3d|--bulk) KPATH_TASK=303 ;;
esac

# Shared helpers (vasp_common.sh): next to this script, else on PATH
_lib="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/vasp_common.sh"; [ -f "$_lib" ] || _lib=$(command -v vasp_common.sh || true)
[ -n "$_lib" ] || { echo "ERROR: vasp_common.sh not found (next to this script or on PATH)" >&2; exit 1; }
source "$_lib"

# Submission script: header-limited scan (first 4 KB), asks if there are several ($RUNSCRIPT overrides)
SUBMISSION_SCRIPT=$(find_runscript)
[ -z "$SUBMISSION_SCRIPT" ] && echo -e "\033[33mWARNING:\033[0m no #PBS/#SBATCH submission script found (or none selected) in $PWD"
COPY_FILES_NEEDED="INCAR POSCAR POTCAR $SUBMISSION_SCRIPT"
LN_FILES_NEEDED="CHGCAR WAVECAR"
NEW_DIRECTORY="BAND"

echo "---------------------------------------------------------"
HSE_CHECK=$(incar_get LHFCALC | grep -iE "^\.?T")
if [ -n "$HSE_CHECK" ] ; then
        echo -e "\033[31mHSE\033[0m calculation!"
        cat <<EOF
*********************************************************
Classical HSE Band Structure Calculation:
1. 303 and 251 to generate the KPOINTS
2. Run PBE calculation using this KPOINTS
3. Run HSE calculation with WAVECAR
4. Run HSE NON-SC calculation
*********************************************************
Wannier90 HSE Band Structure Calculation:
1. Use simple k-mesh KPOINTS (e.g., gamma-centered)
2. Run PBE calculation
3. Run HSE calculation with WAVECAR
4. Run HSE NON-SC calculation
5. Turn on the Wannier90 interface (ICHARG=11)
*********************************************************
EOF
echo "---------------------------------------------------------"
	exit
fi


if [ ! -d $NEW_DIRECTORY ] ; then
	mkdir $NEW_DIRECTORY 
	echo -e "$NEW_DIRECTORY directory created!"
	echo "---------------------------------------------------------"
fi

for files in $COPY_FILES_NEEDED ; do
	if [ -s $files ] ; then
		cp $files $NEW_DIRECTORY 
		echo "'$files' -> '$NEW_DIRECTORY/$files'"
	else
		echo -e "\033[31mERROR:\033[0m $files does not exist or is an empty file!"
		echo "---------------------------------------------------------"
		exit
	fi
done


METAGGA_CHECK=$(incar_get METAGGA)
# Define the ln_file function
ln_file() {
	# If the METAGGA_CHECK variable is not empty, set the file variable to WAVECAR; otherwise, set it to CHGCAR
	if [[ -n "$METAGGA_CHECK" ]]; then
		file="WAVECAR"
	else
		file="CHGCAR"
	fi

    # Check if the file variable is a non-empty file in the current directory
    if [[ ! -s "$file" ]]; then
        echo -e "\033[31mERROR:\033[0m $file does not exist or is an empty file!"
    fi
    cd $NEW_DIRECTORY && ln -s ../"$file" . 
    echo "'$file' -> '$NEW_DIRECTORY/$file'"
    cd ..
    echo "---------------------------------------------------------"
}

# Call the ln_file function
# ln_file

file_editor (){ 
	cd $NEW_DIRECTORY
	if [[ ! -n "$METAGGA_CHECK" ]]; then
		incar_set ICHARG 11 INCAR "(Non-self-consistent: GGA/LDA band structures)"
	fi
	incar_set NSW 0 INCAR "(Non SCF calculation)"
	incar_set IBRION -1 INCAR "(Non SCF calculation)"
	incar_set LWAVE .FALSE. INCAR "(Write WAVECAR or not)"
	incar_set LCHARG .FALSE. INCAR "(Write CHGCAR or not)"
	incar_set LORBIT 11 INCAR "(11 for projected DOS)"
	grep -iE "^[[:space:]]*(NSW|LORBIT|IBRION|LCHARG|LWAVE|ICHARG)[[:space:]]*=" INCAR | awk -F "#" '{print $1}'
	if { [[ ! -n "$METAGGA_CHECK" ]] && [[ "$(incar_get ICHARG)" != "11" ]]; } || [[ "$(incar_get NSW)" != "0" ]]; then
		echo -e "\033[31mERROR:\033[0m INCAR in $NEW_DIRECTORY does not have ICHARG = 11 / NSW = 0 after editing. Aborting."
		exit 1
	fi
	cd ..
}

kpoints_vaspkit_generation (){
    cd $NEW_DIRECTORY
	local vacuum=$(poscar_vacuum_c POSCAR)
	local task="${KPATH_TASK:-}"
	if [[ -z "$task" ]]; then
		if awk -v v="$vacuum" 'BEGIN { exit !(v > 8) }'; then task=302; else task=303; fi
	fi
	echo -e "${task}\n"| vaspkit 1>/dev/null
	echo -e "'KPATH.in' generated by vaspkit ${task} ($([ "$task" = 302 ] && echo 2D || echo bulk); largest vacuum gap along c: ${vacuum} Å)"
	# cp PRIMCELL.vasp POSCAR
	# echo -e "'PRIMCELL.vasp' -> 'POSCAR'"
	if [[ -n "$METAGGA_CHECK" ]]; then
		echo -e "\033[31mMETAGGA\033[0m calculation!"
		echo -e "251\n2\n0.02\n0.04\n"| vaspkit 1>/dev/null
		echo -e "'KPOINTS' for METAGGA generated!"
	else
		echo -e "\033[31mPBE\033[0m calculation!"
		echo -e "'KPOINTS' generating ..."
		cp KPATH.in KPOINTS
		echo -e "'KPATH.in' -> 'KPOINTS'"
	fi
    cd ..
}


echo "---------------------------------------------------------"
file_editor
echo "---------------------------------------------------------"
kpoints_vaspkit_generation
echo -e "Remember to copy \033[31mPRIMCELL.vasp\033[0m to POSCAR if necessary!"
ln_file
echo "---------------------------------------------------------"
